def _rotl(x, r):
    return ((x << r) | (x >> (8 - r))) & 0xFF if r else x


def _rotr(x, r):
    return ((x >> r) | (x << (8 - r))) & 0xFF if r else x


def key_byte(offset):
    j = offset % PERIOD
    v = (j & 0xFF) + (j >> 8)
    return SBOX[v & 0xFF]


def rotation(offset):
    j = offset % PERIOD
    v = (j & 0xFF) + (j >> 8)
    return (v >> 3) & 7


def _tables(decrypt):
    """One 256 byte translation table per position in the period."""
    out = []
    for j in range(PERIOD):
        v = (j & 0xFF) + (j >> 8)
        k, r = SBOX[v & 0xFF], (v >> 3) & 7
        if decrypt:
            out.append(bytes(_rotr(c ^ k, r) for c in range(256)))
        else:
            out.append(bytes(_rotl(p, r) ^ k for p in range(256)))
    return out


_DEC = None
_ENC = None


def _apply(data, offset, tables):
    """Translate each residue class of the period with its own table. All the
    work is done by bytes.translate and slice assignment, so this runs at
    C speed even for a 32 MiB image."""
    data = bytes(data)
    out = bytearray(len(data))
    for j in range(PERIOD):
        start = (j - offset) % PERIOD
        if start >= len(data):
            continue
        out[start::PERIOD] = data[start::PERIOD].translate(tables[j])
    return bytes(out)


def decrypt(data, offset=0):
    """Decrypt a slice of the image whose first byte sits at `offset`."""
    global _DEC
    if _DEC is None:
        _DEC = _tables(True)
    return _apply(data, offset, _DEC)


def encrypt(data, offset=0):
    global _ENC
    if _ENC is None:
        _ENC = _tables(False)
    return _apply(data, offset, _ENC)


def looks_encrypted(data):
    """An encrypted image has about 0.4% zero bytes, a plain one about 16%."""
    sample = data[:1 << 20]
    return sample.count(0) / max(len(sample), 1) < 0.05
